// == (equality)
console.log("--- == (EQUALITY) ---")
console.log(`5 == "5" : ${5 == "5"}`)
console.log(`5 == 5 : ${5 == 5}`)

// != (inequality)
console.log("--- != (INEQUALITY) ---")
console.log(`5 != 5 : ${5 != 5}`)
console.log(`5 != "5" : ${5 != "5"}`)

// === (strict equality)
console.log("--- === (STRICT EQUALITY) ---")
console.log(`5 === 5 : ${5 === 5}`)
console.log(`5 === "5" : ${5 === "5"}`)

// !== (strict inequality)
console.log("--- !== (STRICT INEQUALITY) ---")
console.log(`5 !== 5 : ${5 !== 5}`)
console.log(`5 !== "5" : ${5 !== "5"}`)

// >
console.log("--- > (GREATER THAN) ---")
console.log(`10 > 7 : ${10 > 7}`)
console.log(`10 > 10 : ${10 > 10}`)

// >=
console.log("--- >= (GREATHER THAN OR EQUAL TO) ---")
console.log(`10 >= 7 : ${10 >= 7}`)
console.log(`10 >= 10 : ${10 >= 10}`)

// <
console.log("--- < (LESS THAN) ---")
console.log(`10 < 7 : ${10 < 7}`)
console.log(`10 < 10 : ${10 < 10}`)

// <=
console.log("--- <= (LESS THAN OR EQUQL TO) ---")
console.log(`10 <= 7 : ${10 <= 7}`)
console.log(`10 <= 10 : ${10 <= 10}`)